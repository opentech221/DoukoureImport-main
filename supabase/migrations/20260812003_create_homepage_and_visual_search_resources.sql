on conflict (id) do nothing;

-- Storage policies for public upload/read on the specific bucket
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'storage'
      AND tablename = 'objects'
      AND policyname = 'search_uploads_public_read'
  ) THEN
    CREATE POLICY search_uploads_public_read
      ON storage.objects
      FOR SELECT
      TO public
      USING (bucket_id = 'search-uploads');
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'storage'
      AND tablename = 'objects'
      AND policyname = 'search_uploads_anon_insert'
  ) THEN
    CREATE POLICY search_uploads_anon_insert
      ON storage.objects
      FOR INSERT
      TO anon, authenticated
      WITH CHECK (bucket_id = 'search-uploads');
  END IF;
END $$;

