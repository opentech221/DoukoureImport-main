-- ---------------------------------------------------------------------------
-- 5) Trigger to auto-track status transitions
-- ---------------------------------------------------------------------------
create or replace function public.log_order_status_transition()
returns trigger
language plpgsql
as $$
begin
  if new.status is distinct from old.status then
    insert into public.order_status_events (
      order_ref,
      previous_status,
      next_status,
      source,
      metadata
    )
    values (
      new.order_ref,
      old.status,
      new.status,
      'db_trigger',
      jsonb_build_object('updated_at', new.updated_at)
    );
  end if;

  return new;
end;
$$;

drop trigger if exists trg_log_order_status_transition on public.orders;
create trigger trg_log_order_status_transition
after update on public.orders
for each row
execute function public.log_order_status_transition();

