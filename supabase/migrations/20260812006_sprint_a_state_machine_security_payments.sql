-- ---------------------------------------------------------------------------
-- 2) Order transition events (state machine observability)
-- ---------------------------------------------------------------------------
create table if not exists public.order_status_events (
  id bigint generated by default as identity primary key,
  order_ref text not null,
  previous_status text,
  next_status text not null,
  source text not null default 'unknown',
  metadata jsonb,
  created_at timestamptz not null default now()
);

create index if not exists idx_order_status_events_order_ref
  on public.order_status_events(order_ref, created_at desc);

comment on table public.order_status_events is 'Immutable log of order lifecycle status transitions';

-- ---------------------------------------------------------------------------
-- 3) Payment transactions (idempotency and reconciliation)
-- ---------------------------------------------------------------------------
create table if not exists public.payment_transactions (
  id bigint generated by default as identity primary key,
  order_ref text not null,
  provider text not null check (provider in ('wave', 'orange')),
  provider_reference text not null,
  amount_xof bigint not null check (amount_xof >= 0),
  status text not null check (status in ('PENDING', 'CONFIRMED', 'FAILED')),
  idempotency_key text not null,
  payer_name text,
  payer_phone text,
  metadata jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (provider, provider_reference),
  unique (provider, idempotency_key)
);

create index if not exists idx_payment_transactions_order_ref
  on public.payment_transactions(order_ref, created_at desc);

comment on table public.payment_transactions is 'Payment attempts and confirmations for Wave/Orange Money';

-- ---------------------------------------------------------------------------
